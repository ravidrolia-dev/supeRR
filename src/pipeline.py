"""
ClutchIQ - Master Pipeline Orchestrator
Coordinates loaders, delivery feature engineering, and aggregations.
Generates all 5 output datasets in data/processed/.
"""

import sys
import logging
from pathlib import Path
import pandas as pd

from src.config import OUTPUT_DIR, DATA_AUDIT_DIR
from src.loaders import load_raw_data, build_match_context, build_player_lookup
from src.delivery_features import engineer_master_ball_by_ball
from src.aggregated_features import build_batting_features, build_bowling_features

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    handlers=[
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger("ClutchIQ.Pipeline")


def run_master_pipeline() -> None:
    """Execute end-to-end data processing pipeline."""
    logger.info("=== Starting ClutchIQ Master Processing Pipeline ===")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Load Raw Source Data
    raw = load_raw_data()

    # 2. Load Unresolved Deliveries if generated by data_audit
    unresolved_file = DATA_AUDIT_DIR / "unresolved_deliveries.csv"
    unresolved_df = None
    if unresolved_file.exists():
        logger.info(f"Loading unresolved deliveries from {unresolved_file}...")
        unresolved_df = pd.read_csv(unresolved_file)

    # 3. Build Match Context & Player Lookup
    match_context = build_match_context(raw["matches"], raw["competitions"])
    player_lookup = build_player_lookup(raw["ctpm"], raw["playing_eleven"], raw["ball_by_ball"])

    # Save match_context and player_lookup
    match_context_path = OUTPUT_DIR / "match_context.csv"
    match_context.to_csv(match_context_path, index=False)
    logger.info(f"Saved: {match_context_path} ({len(match_context)} rows)")

    player_lookup_path = OUTPUT_DIR / "player_lookup.csv"
    player_lookup.to_csv(player_lookup_path, index=False)
    logger.info(f"Saved: {player_lookup_path} ({len(player_lookup)} rows)")

    # 4. Build Master Ball-by-Ball Dataset
    master_bbb = engineer_master_ball_by_ball(raw["ball_by_ball"], match_context, unresolved_df)
    master_bbb_path = OUTPUT_DIR / "master_ball_by_ball.csv"
    master_bbb.to_csv(master_bbb_path, index=False)
    logger.info(f"Saved: {master_bbb_path} ({len(master_bbb):,} rows, {len(master_bbb.columns)} cols)")

    # 5. Build Aggregated Batting & Bowling Features (IPL + Senior T20I scope)
    batting_features = build_batting_features(master_bbb)
    batting_features_path = OUTPUT_DIR / "batting_features.csv"
    batting_features.to_csv(batting_features_path, index=False)
    logger.info(f"Saved: {batting_features_path} ({len(batting_features):,} rows)")

    bowling_features = build_bowling_features(master_bbb)
    bowling_features_path = OUTPUT_DIR / "bowling_features.csv"
    bowling_features.to_csv(bowling_features_path, index=False)
    logger.info(f"Saved: {bowling_features_path} ({len(bowling_features):,} rows)")

    logger.info("=== ClutchIQ Master Processing Pipeline Completed Successfully! ===")


if __name__ == "__main__":
    run_master_pipeline()

